% فرض می‌کنیم داده‌ها در ورک‌اسپیس با نام‌های tout و tankheight موجود هستند
% اگر نامشان فرق دارد، آن‌ها را جایگزین کنید (مثلاً H و t)

% 1. پیدا کردن مقدار نهایی (Steady State)
y_final = mean(tankheight(end-50:end)); % میانگین ۵۰ داده آخر برای دقت بیشتر
disp(['Final Height (K_sys): ', num2str(y_final)]);

% 2. پیدا کردن ثابت زمانی (Tau)
% ثابت زمانی جایی است که خروجی به 63.2 درصد مقدار نهایی می‌رسد
target_value = 0.632 * y_final;

% پیدا کردن اولین اندیسی که ارتفاع از این مقدار رد می‌شود
idx = find(tankheight >= target_value, 1);
tau = tout(idx); 
disp();

% 3. تشکیل تابع تبدیل
s = tf('s');
G = y_final / (tau * s + 1);

